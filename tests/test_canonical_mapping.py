# --- 10. end-to-end: real .sysml -> Snapshot -> Canonical Model ---


def test_perform_probe_maps_end_to_end() -> None:
    snapshot = OpenSysMLFileAdapter().load(VALID_MODEL)
    model = CanonicalSystemMapper().map_snapshot(snapshot)
    assert model.system.id == "system-1"
    assert model.system.name == "hydraulicPump"
    assert (
        model.system.source_refs[0].source_element_id
        == "PerformProbe::hydraulicPump"
    )
    assert model.system.source_refs[0].source_uri == str(VALID_MODEL.resolve())
    components = {c.name: c for c in model.components}
    assert set(components) == {"motor"}
    assert components["motor"].id == "component-1"
    assert components["motor"].parent_id == "system-1"
    assert (
        components["motor"].source_refs[0].source_element_id
        == "PerformProbe::hydraulicPump::motor"
    )
    functions = {f.name: f for f in model.functions}
    assert set(functions) == {"spin"}
    assert functions["spin"].id == "function-1"
    assert (
        functions["spin"].source_refs[0].source_element_id == "PerformProbe::spin"
    )
    notice_pairs = _notice_pairs(model)
    assert ("PerformProbe", "TENTATIVE") in notice_pairs
    assert ("PerformProbe::Pump", "NEEDS_RESEARCH") in notice_pairs
    assert ("PerformProbe::Motor", "NEEDS_RESEARCH") in notice_pairs
    assert ("PerformProbe::Spin", "NEEDS_RESEARCH") in notice_pairs
    assert ("PerformProbe::Spin::speed", "DEFERRED") in notice_pairs
    assert ("PerformProbe::hydraulicPump::motor::spin", "NEEDS_RESEARCH") in notice_pairs
    assert len(model.notices) == 6
    for entity in [model.system, *model.components, *model.functions]:
        assert entity.id != entity.source_refs[0].source_element_id


def test_sibling_roots_model_requires_explicit_root() -> None:
    snapshot = OpenSysMLFileAdapter().load(SIBLING_ROOTS_MODEL)
    with pytest.raises(CanonicalMappingError, match="multiple PartUsage candidates"):
        CanonicalSystemMapper().map_snapshot(snapshot)
    model = CanonicalSystemMapper().map_snapshot(
        snapshot, root_source_id="AlphaPackage::alphaPump"
    )
    assert model.system.name == "alphaPump"
    assert [c.name for c in model.components] == ["alphaInner"]
    assert model.components[0].parent_id == "system-1"
    notice_pairs = _notice_pairs(model)
    assert ("AlphaPackage::alphaMotor", "DEFERRED") in notice_pairs
    assert ("BetaPackage::betaPump", "DEFERRED") in notice_pairs


def test_no_usage_model_raises_canonical_mapping_error() -> None:
    snapshot = OpenSysMLFileAdapter().load(NO_USAGE_MODEL)
    with pytest.raises(CanonicalMappingError, match="no named PartUsage candidate"):
        CanonicalSystemMapper().map_snapshot(snapshot)


def test_invalid_model_partial_snapshot_maps_observed_facts() -> None:
    snapshot = OpenSysMLFileAdapter().load(INVALID_MODEL)
    model = CanonicalSystemMapper().map_snapshot(snapshot)
    assert model.system.name == "broken"
    assert model.system.source_refs[0].source_element_id == "BrokenProbe::broken"
